def system_language():
    for key in ("LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        value = os.environ.get(key, "")
        if value:
            locale = value.lower().replace("-", "_")
            if locale.startswith("ru"):
                return "ru"
            if locale.startswith("pt"):
                return "pt_BR"
            if locale.startswith("zh"):
                return "zh_CN"
            if locale.startswith("fr"):
                return "fr_FR"
            return "en"
    return "en"


_language = "ru"


def set_language(choice):
    """choice: "ru", "en", "pt", "pt_BR", "zh_CN", "fr_FR" or "" (the system's)."""
    global _language
    if choice in ("pt", "pt_BR"):
        _language = "pt_BR"
    elif choice in ("ru", "en", "zh_CN", "fr_FR"):
        _language = choice
    else:
        _language = system_language()


def language():
    return _language


def tr(text):
    if _language == "en":
        return EN.get(text, text)
    if _language in ("pt", "pt_BR"):
        # Strings in PT_BR override PT; strings missing in both fall back to English.
        return PT_BR.get(text, PT.get(text, EN.get(text, text)))
    if _language == "zh_CN":
        return ZH_CN.get(text, EN.get(text, text))
    if _language == "fr_FR":
        return FR_FR.get(text, EN.get(text, text))
    return text

